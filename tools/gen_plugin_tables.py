"""Generate plugins/resolve/tables.h from the effect registry, so every effect is in the plugin with its real controls."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from badcamera import presets, serve  # noqa: E402

GROUPS = {"Tape & Camera": "tape vhs camcorder_sensor night_vision crt interlace ccd_smear sensor_noise camera_life frame_rate",
          "Film & Lens": "grain film_damage bleach_bypass light_leak lens_flare lightburst chromatic_aberration bloom vignette flash overlay",
          "Digital": "jpeg datamosh lcd bit_depth blur_pixelate noise", "Picture": "color_grade lut gaussian_blur sharpen clarity bilateral desaturate text_stamp"}
ACRONYMS = {"vhs": "VHS", "lut": "LUT", "jpeg": "JPEG", "lcd": "LCD", "crt": "CRT", "ir": "IR", "agc": "AGC", "ccd": "CCD"}


def pretty(name):
    return " ".join(ACRONYMS.get(w, w.capitalize()) for w in name.split("_"))


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


rows, groups = [], {t: g for g, ts in GROUPS.items() for t in ts.split()}
missing = [e["type"] for e in serve.manifest() if e["type"] not in groups]
assert not missing, f"add these to GROUPS: {missing}"
out = ["// Generated by tools/gen_plugin_tables.py. Don't edit.", "#pragma once", "#include <vector>", '#include "plugin_types.h"', "static const std::vector<EffectDef> EFFECTS = {"]
for e in serve.manifest():
    ps = []
    for p in e["params"]:
        d = p["default"]
        vec = [float(x) for x in d] if isinstance(d, list) else [0.0, 0.0, 0.0]
        scalar = float(d) if p["kind"] in ("float", "int", "bool") else 0.0
        opts = ", ".join(q(o) for o in (p["options"] or []))
        text = q(d if p["kind"] in ("text", "enum") else "")
        ps.append(f'{{{q(p["key"])}, {q(pretty(p["key"]))}, {q(p["kind"])}, {scalar}, {p["lo"]}, {p["hi"]}, {{{vec[0]}, {vec[1]}, {vec[2]}}}, {text}, {{{opts}}}}}')
    out.append(f'  {{{q(e["type"])}, {q(pretty(e["type"]))}, {q(groups[e["type"]])}, {{\n    ' + ",\n    ".join(ps) + "}},")
out.append("};")
out.append("static const std::vector<const char*> BUILTIN_PRESETS = {" + ", ".join(q(p["name"]) for p in presets.builtin()) + "};")
Path("plugins/resolve/tables.h").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(serve.manifest())} effects, {len(presets.builtin())} presets")
